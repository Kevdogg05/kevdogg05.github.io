// Kid-friendly burned-in captions, as an ASS subtitle file for ffmpeg/libass.
//
// Words are grouped into short lines (a few big words at a time), shown in the
// lower third in a rounded bold font with a thick outline. The word being
// spoken pops in a bright colour, and each line takes the next colour from a
// rainbow palette, karaoke style.

import type { TranscriptWord } from "@/lib/types";

export interface CaptionWord {
  text: string;
  start: number;
  end: number;
}

export interface CaptionLine {
  start: number;
  end: number;
  words: CaptionWord[];
}

export interface CaptionLayout {
  width: number;
  height: number;
  fontName: string;
}

/** Highlight colours as #RRGGBB: sunshine, sky, bubblegum, lime, tangerine, lilac. */
export const CAPTION_PALETTE = ["#FFD60A", "#2EE6FF", "#FF5FD2", "#7CFF4F", "#FF9F1C", "#B69CFF"];
const TEXT_COLOUR = "#FFFFFF";
const OUTLINE_COLOUR = "#3D1A55";

/** ASS wants &HBBGGRR& (optionally with alpha first). */
export function assColour(hex: string, alpha = 0): string {
  const [r, g, b] = [1, 3, 5].map((i) => hex.slice(i, i + 2).toUpperCase());
  return `&H${alpha.toString(16).padStart(2, "0").toUpperCase()}${b}${g}${r}`;
}

/** H:MM:SS.cc, the timestamp format ASS uses (centiseconds). */
export function assTime(seconds: number): string {
  const cs = Math.max(0, Math.round(seconds * 100));
  const h = Math.floor(cs / 360_000);
  const m = Math.floor((cs % 360_000) / 6000);
  const s = Math.floor((cs % 6000) / 100);
  return `${h}:${String(m).padStart(2, "0")}:${String(s).padStart(2, "0")}.${String(cs % 100).padStart(2, "0")}`;
}

/** Strips characters ASS would read as override tags. */
function clean(text: string): string {
  return text.replace(/[{}\\]/g, "").replace(/\s+/g, " ").trim();
}

export function fontSizeFor(layout: Pick<CaptionLayout, "width" | "height">): number {
  return Math.round(Math.min(layout.width, layout.height) * 0.095);
}

/** Roughly how many characters fit on one line at the caption font size. */
export function maxCharsFor(layout: Pick<CaptionLayout, "width" | "height">): number {
  return Math.max(8, Math.floor((layout.width * 0.86) / (fontSizeFor(layout) * 0.62)));
}

export interface GroupOptions {
  maxChars: number;
  maxWords: number;
  /** Longest a line stays up (seconds). */
  maxDuration: number;
  /** A gap longer than this between words starts a new line. */
  maxGap: number;
  /** How long a line lingers after its last word, if nothing follows. */
  linger: number;
}

const DEFAULT_GROUPING: Omit<GroupOptions, "maxChars"> = { maxWords: 5, maxDuration: 2.6, maxGap: 0.6, linger: 0.5 };

export function groupCaptionLines(words: TranscriptWord[], options: Partial<GroupOptions> & { maxChars: number }): CaptionLine[] {
  const o = { ...DEFAULT_GROUPING, ...options };
  const lines: CaptionLine[] = [];
  let current: CaptionWord[] = [];

  const flush = () => {
    if (current.length) lines.push({ start: current[0].start, end: current.at(-1)!.end, words: current });
    current = [];
  };

  for (const raw of [...words].sort((a, b) => a.start_us - b.start_us)) {
    const text = clean(raw.text);
    if (!text) continue;
    const word = { text, start: raw.start_us / 1e6, end: Math.max(raw.end_us, raw.start_us) / 1e6 };
    const previous = current.at(-1);
    if (previous) {
      const chars = current.reduce((sum, w) => sum + w.text.length + 1, 0) + text.length;
      if (
        chars > o.maxChars ||
        current.length >= o.maxWords ||
        word.start - previous.end > o.maxGap ||
        word.end - current[0].start > o.maxDuration ||
        /[.!?]$/.test(previous.text)
      ) {
        flush();
      }
    }
    current.push(word);
  }
  flush();

  // Let each line linger a little, but never into the next one.
  return lines.map((line, i) => {
    const next = lines[i + 1];
    const end = Math.max(line.end, line.start + 0.4) + o.linger;
    return { ...line, end: next ? Math.min(end, next.start) : end };
  });
}

export function buildAss(lines: CaptionLine[], layout: CaptionLayout): string {
  const size = fontSizeFor(layout);
  const outline = Math.max(2, Math.round(size * 0.1));
  const shadow = Math.max(1, Math.round(size * 0.05));
  const marginV = Math.round(layout.height * 0.14);
  const marginH = Math.round(layout.width * 0.06);
  const white = `${assColour(TEXT_COLOUR)}&`;

  const header = [
    "[Script Info]",
    "; Generated by SnS Palace",
    "ScriptType: v4.00+",
    `PlayResX: ${layout.width}`,
    `PlayResY: ${layout.height}`,
    "WrapStyle: 0",
    "ScaledBorderAndShadow: yes",
    "YCbCr Matrix: TV.709",
    "",
    "[V4+ Styles]",
    "Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding",
    `Style: Kid,${layout.fontName},${size},${assColour(TEXT_COLOUR)},${assColour(TEXT_COLOUR)},${assColour(OUTLINE_COLOUR)},${assColour("#000000", 0x80)},-1,0,0,0,100,100,1,0,1,${outline},${shadow},2,${marginH},${marginH},${marginV},1`,
    "",
    "[Events]",
    "Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text",
  ];

  const events: string[] = [];
  lines.forEach((line, lineIndex) => {
    const highlight = `${assColour(CAPTION_PALETTE[lineIndex % CAPTION_PALETTE.length])}&`;
    line.words.forEach((word, wordIndex) => {
      // One event per word: the line stays put while the highlight moves along.
      const start = wordIndex === 0 ? line.start : word.start;
      const end = wordIndex === line.words.length - 1 ? line.end : line.words[wordIndex + 1].start;
      if (end <= start) return;
      const text = line.words
        .map((w, i) => (i === wordIndex ? `{\\c${highlight}\\fscx114\\fscy114}${w.text}{\\c${white}\\fscx100\\fscy100}` : w.text))
        .join(" ");
      const fadeIn = wordIndex === 0 ? "{\\fad(80,0)}" : "";
      events.push(`Dialogue: 0,${assTime(start)},${assTime(end)},Kid,,0,0,0,,${fadeIn}${text}`);
    });
  });

  return [...header, ...events, ""].join("\n");
}
