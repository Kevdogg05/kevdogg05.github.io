"""Embed ../web/index.html into the firmware as a gzipped C array.

The dashboard has one source, web/index.html. This script gzips it into
include/web_index.h (gitignored), which main.cpp serves at "/" with
Content-Encoding: gzip.

PlatformIO runs it before every build (extra_scripts = pre:scripts/embed_web.py).
It also runs on its own, which the arduino-cli build in ../Makefile uses:

    python3 scripts/embed_web.py [--firmware-dir DIR]

The header is only rewritten when its contents change, so an unchanged
dashboard does not trigger a rebuild.
"""

import argparse
import gzip
import hashlib
import os
import sys


def paths(firmware_dir):
    source = os.path.normpath(os.path.join(firmware_dir, "..", "web", "index.html"))
    target = os.path.join(firmware_dir, "include", "web_index.h")
    return source, target


def render_header(html, source_name):
    packed = gzip.compress(html, compresslevel=9, mtime=0)  # mtime=0: reproducible bytes
    digest = hashlib.sha256(html).hexdigest()[:16]
    rows = []
    for i in range(0, len(packed), 16):
        rows.append("  " + ", ".join("0x%02x" % b for b in packed[i : i + 16]) + ",")
    return (
        "// Generated by scripts/embed_web.py from %s. Do not edit.\n"
        "// source: %d bytes, sha256 %s; gzip: %d bytes\n"
        "#pragma once\n"
        "#include <stddef.h>\n"
        "#include <stdint.h>\n\n"
        "static const size_t WEB_INDEX_HTML_GZ_LEN = %d;\n"
        "static const uint8_t WEB_INDEX_HTML_GZ[] = {\n%s\n};\n"
        % (source_name, len(html), digest, len(packed), len(packed), "\n".join(rows))
    ), len(packed)


def embed(firmware_dir, quiet=False):
    source, target = paths(firmware_dir)
    if not os.path.isfile(source):
        raise SystemExit("embed_web: dashboard not found at %s" % source)
    with open(source, "rb") as f:
        html = f.read()
    text, packed_len = render_header(html, "web/index.html")

    current = None
    if os.path.isfile(target):
        with open(target, "r", encoding="utf-8") as f:
            current = f.read()
    if current != text:
        os.makedirs(os.path.dirname(target), exist_ok=True)
        with open(target, "w", encoding="utf-8") as f:
            f.write(text)
    if not quiet:
        state = "updated" if current != text else "unchanged"
        print("embed_web: web/index.html %.1f KB -> %.1f KB gzip (%s)" % (len(html) / 1024, packed_len / 1024, state))
    return target


def main(argv):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--firmware-dir",
        default=os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
        help="firmware project folder (default: the folder above this script)",
    )
    args = parser.parse_args(argv)
    embed(args.firmware_dir)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
else:
    # Running inside PlatformIO's SCons, which provides Import() and has no __file__.
    Import("env")  # noqa: F821
    embed(env.subst("$PROJECT_DIR"))  # noqa: F821
